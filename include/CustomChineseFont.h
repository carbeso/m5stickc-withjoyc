/**
 * @brief 查找漢字點陣
 */
inline const uint16_t* getGlyphBitmap(const char* utf8Char) {
    for (uint8_t i = 0; i < GLYPH_COUNT; i++) {
        if (strcmp(CHINESE_GLYPHS[i].utf8, utf8Char) == 0) {
            return CHINESE_GLYPHS[i].rows;
        }
    }
    // 若無匹配則返回 "大"
    return CHINESE_GLYPHS[0].rows;
}
